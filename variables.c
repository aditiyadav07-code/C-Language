#include<stdio.h>
int main()
{
    int a=10; // Variable is int
    int b=5; //Variable name is b
    /*multiple
    comments*/
    printf("a is: 10\n");
    printf("b is: 5\n");
    printf("The sum of a and b is: %d\n", a+b);
    printf("The sub of a and b is: %d\n", a-b);
    printf("The mult of a and b is: %d\n", a*b);
    printf("The div of a and b is: %d\n", a/b);
    printf("The mod of a and b is: %d\n", a%b);
    char c='A';
    float f=3.14;
    printf("Char: %c", c);
    printf("\nFloat: %.2f", f);
    return 0;
}